package org.ghostsinthelab.app.phahtaibundroid.dictbuilder

import org.ghostsinthelab.app.phahtaibundroid.core.lexicon.Lexicon
import org.ghostsinthelab.app.phahtaibundroid.core.lexicon.LexiconEntry
import org.ghostsinthelab.app.phahtaibundroid.core.romanization.Romanization
import org.ghostsinthelab.app.phahtaibundroid.core.romanization.Syllable
import java.io.File
import java.text.Normalizer

/**
 * A ChhoeTaigi dataset (https://github.com/ChhoeTaigi/ChhoeTaigiDatabase) to include.
 * Only permissively licensed datasets are used, since the result ships inside the APK.
 */
private class Source(val file: String, val label: String, val license: String, val weight: Int)

private val SOURCES = listOf(
    Source("ChhoeTaigi_TaihoaSoanntengTuichiautian.csv", "台文華文線頂辭典 (Tēⁿ Liông-úi, Iûⁿ Ún-giân et al.)", "CC BY-SA 4.0", 2),
    Source("ChhoeTaigi_iTaigiHoataiTuichiautian.csv", "iTaigi 華台對照典", "CC0", 3),
)

/** Hàn-lô containing these is an explanation or example sentence, not a word. */
private val REJECTED_HANLO = Regex("[，。；：、？！,.;:?!「」『』〔〕…]")
private val ANNOTATION = Regex("\\[[^]]*]|\\([^)]*\\)|（[^）]*）")

private class Stats {
    var rows = 0
    var added = 0
    var skippedHanlo = 0
    var skippedRoman = 0
}

fun main(args: Array<String>) {
    require(args.size == 2) { "usage: dictbuilder <sources-dir> <output.tsv>" }
    val sourcesDir = File(args[0])
    val output = File(args[1])

    // (hanlo, numeric) → accumulated entry
    data class Key(val hanlo: String, val numeric: String)
    val weights = LinkedHashMap<Key, Int>()
    val pojHanlo = HashMap<Key, String>()

    for (source in SOURCES) {
        val file = File(sourcesDir, source.file)
        require(file.isFile) { "missing $file — run scripts/fetch-lexicon-sources.sh" }
        val stats = Stats()
        val rows = Csv.read(file)
        val header = rows.first().map { it.trim('﻿') }
        fun List<String>.col(name: String) = header.indexOf(name).let { if (it >= 0) getOrNull(it).orEmpty().trim() else "" }

        for (row in rows.drop(1)) {
            stats.rows++
            val hanloForms = cleanHanlo(row.col("HanLoTaibunKip"))
            val hanloPojForms = cleanHanlo(row.col("HanLoTaibunPoj"))
            if (hanloForms.isEmpty()) {
                stats.skippedHanlo++
                continue
            }
            val readings = buildList {
                row.col("KipUnicode").split('/').forEach { add(it to source.weight) }
                row.col("KipUnicodeOthers").split('/', '、').forEach { add(it to 1) }
            }.filter { it.first.isNotBlank() }

            var any = false
            for ((readingIndex, reading) in readings.withIndex()) {
                val (text, weight) = reading
                // Fall back to the numeric column, which is occasionally cleaner than the Unicode one.
                val syllables = Romanization.parseWord(text)
                    ?: (if (readingIndex == 0) Romanization.parseWord(row.col("KipInput").substringBefore('/')) else null)
                    ?: continue
                val numeric = toNumeric(syllables)
                // Pair the n-th reading with the n-th written form where the source lists several.
                val i = if (hanloForms.size == readings.size) readingIndex else 0
                val key = Key(hanloForms[i], numeric)
                weights[key] = (weights[key] ?: 0) + weight
                hanloPojForms.getOrNull(i)?.takeIf { it != key.hanlo }?.let { pojHanlo[key] = it }
                any = true
            }
            if (any) stats.added++ else stats.skippedRoman++
        }
        println("${source.file}: ${stats.rows} rows, ${stats.added} used, " +
            "${stats.skippedHanlo} without usable Hàn-lô, ${stats.skippedRoman} with unparseable romanization")
    }

    val entries = weights.entries
        .map { (k, w) -> LexiconEntry(k.hanlo, pojHanlo[k], k.numeric, w) }
        .sortedWith(compareBy({ it.romanization.lowercase() }, { -it.weight }, { it.hanlo }))

    output.parentFile.mkdirs()
    output.bufferedWriter(Charsets.UTF_8).use { out ->
        out.append("# Phah Taibun Droid lexicon — generated by tools/dictbuilder; do not edit.\n")
        out.append("# Format: hanlo<TAB>numeric-tailo<TAB>weight[<TAB>hanlo-poj]\n")
        for (s in SOURCES) out.append("# Source: ${s.label} via ChhoeTaigi, ${s.license}\n")
        Lexicon.writeEntries(entries, out)
    }
    println("wrote ${entries.size} entries to $output (${output.length() / 1024} KiB)")
}

/** Splits `揹/偝[背負]` into `[揹, 偝]`; returns empty if the text isn't a usable word. */
private fun cleanHanlo(raw: String): List<String> {
    val cleaned = Normalizer.normalize(ANNOTATION.replace(raw, ""), Normalizer.Form.NFC)
    if (REJECTED_HANLO.containsMatchIn(cleaned)) return emptyList()
    return cleaned.split('/').map { it.trim() }.filter { it.isNotEmpty() && '\t' !in it }
}

/** Numeric Tâi-lô with implicit tones filled in, keeping capitalization and boundaries. */
private fun toNumeric(syllables: List<Syllable>): String = buildString {
    for ((i, s) in syllables.withIndex()) {
        if (i > 0) append(s.boundary.text)
        append(s.withImplicitTone().toNumeric())
    }
}
